import type { Song, Track } from './score';

type Bar = readonly (readonly [offset: number, pitch: number, length: number])[];

function part(name: string, role: Track['role'], beatsPerBar: number, bars: readonly Bar[], velocity: number | ((beat: number) => number), start = 0): Track {
  return { name, role, notes: bars.flatMap((bar, index) => bar.map(([offset, pitch, length]) => ({
    beat: start + index * beatsPerBar + offset, pitch, length,
    velocity: typeof velocity === 'number' ? velocity : velocity(start + index * beatsPerBar + offset),
  }))) };
}

