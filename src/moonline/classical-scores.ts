import type { Song, Track } from './score';

type Bar = readonly (readonly [offset: number, pitch: number, length: number])[];

function part(name: string, role: Track['role'], beatsPerBar: number, bars: readonly Bar[], velocity: number): Track {
  return { name, role, notes: bars.flatMap((bar, index) => bar.map(([offset, pitch, length]) => ({
    beat: index * beatsPerBar + offset, pitch, length, velocity,
  }))) };
}

